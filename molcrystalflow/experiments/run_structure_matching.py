#!/usr/bin/env python
"""
Run structure matching analysis on inference results.

This script:
1. Loads the .pt file generated by inference
2. Generates ground truth and predicted XYZ files
3. Performs structure matching using pymatgen StructureMatcher
4. Saves RMSD results and matching summary

Usage:
    python experiments/run_structure_matching.py \
        --pt_file path/to/predictions_K.pt \
        --output_dir path/to/output \
        --num_samples K \
        --stol 0.8 \
        --num_cpus 24
"""

import os
import sys
import json
import argparse

# Add project root to path for imports
script_dir = os.path.dirname(os.path.abspath(__file__))
project_root = os.path.dirname(os.path.dirname(script_dir))
sys.path.insert(0, project_root)

from molcrystalflow.data.utils import visualize_predictions
from molcrystalflow.experiments.xyz_matching import match_structures_multi_samples


def main():
    parser = argparse.ArgumentParser(
        description="Run structure matching analysis for MolCrystalFlow inference results."
    )
    parser.add_argument(
        "--pt_file", 
        type=str, 
        required=True,
        help="Path to predictions_K.pt file generated by inference"
    )
    parser.add_argument(
        "--output_dir", 
        type=str, 
        default=None,
        help="Output directory for results (default: same as pt_file directory)"
    )
    parser.add_argument(
        "--num_samples", 
        type=int, 
        required=True,
        help="Number of samples per structure (K in predictions_K.pt)"
    )
    parser.add_argument(
        "--stol", 
        type=float, 
        default=0.8,
        help="Site tolerance for structure matching (default: 0.8)"
    )
    parser.add_argument(
        "--ltol", 
        type=float, 
        default=0.3,
        help="Lattice tolerance for structure matching (default: 0.3)"
    )
    parser.add_argument(
        "--angle_tol", 
        type=float, 
        default=10.0,
        help="Angle tolerance in degrees for structure matching (default: 10.0)"
    )
    parser.add_argument(
        "--num_cpus", 
        type=int, 
        default=24,
        help="Number of CPUs for parallel processing (default: 24)"
    )
    parser.add_argument(
        "--suffix", 
        type=str, 
        default=None,
        help="Suffix for output files (default: derived from pt_file path)"
    )
    parser.add_argument(
        "--cg",
        action="store_true",
        help="Enable coarse-grained structure matching (default: off)"
    )
    args = parser.parse_args()

    # Validate input file
    if not os.path.exists(args.pt_file):
        raise FileNotFoundError(f"Prediction file not found: {args.pt_file}")

    # Set up output directory
    if args.output_dir is None:
        args.output_dir = os.path.dirname(args.pt_file)
    xyz_dir = os.path.join(args.output_dir, "xyz")
    results_dir = os.path.join(args.output_dir, "results")
    os.makedirs(xyz_dir, exist_ok=True)
    os.makedirs(results_dir, exist_ok=True)

    # Derive suffix from path if not provided
    if args.suffix is None:
        # Use the base name of the .pt file without extension
        args.suffix = os.path.splitext(os.path.basename(args.pt_file))[0]
        if not args.suffix:
            args.suffix = "experiment"

    print(f"=" * 60)
    print(f"Structure Matching Analysis")
    print(f"=" * 60)
    print(f"Input file: {args.pt_file}")
    print(f"Output directory: {args.output_dir}")
    print(f"Number of samples: {args.num_samples}")
    print(f"Site tolerance: {args.stol}")
    print(f"Lattice tolerance: {args.ltol}")
    print(f"Angle tolerance: {args.angle_tol}")
    print(f"Number of CPUs: {args.num_cpus}")
    print(f"=" * 60)

    # Step 1: Generate XYZ files from predictions
    print("\n[Step 1] Generating XYZ files from predictions...")
    gt_xyz = f"gt_{args.suffix}.xyz"
    pred_xyz = f"pred_{args.suffix}.xyz"
    cg_xyz = f"cg_pred_{args.suffix}.xyz" if args.cg else None
    cg_gt_xyz = f"cg_gt_{args.suffix}.xyz" if args.cg else None

    save_info = visualize_predictions(
        pred_file=args.pt_file,
        gt_xyz=gt_xyz,
        pred_xyz=pred_xyz,
        save_dir=xyz_dir,
        cg_xyz=cg_xyz,
        cg_gt_xyz=cg_gt_xyz
    )
    print(f"  Ground truth XYZ: {os.path.join(xyz_dir, gt_xyz)}")
    print(f"  Predicted XYZ: {os.path.join(xyz_dir, pred_xyz)}")

    # Step 2: Full structure matching
    print("\n[Step 2] Performing full structure matching...")
    gt_file = os.path.join(xyz_dir, gt_xyz)
    pred_file = os.path.join(xyz_dir, pred_xyz)
    
    output_csv = os.path.join(
        results_dir, 
        f"all_atom_rmsd_results_{args.num_samples}_stol{args.stol}.csv"
    )
    output_json = os.path.join(
        results_dir, 
        f"all_atom_matching_summary_{args.num_samples}_stol{args.stol}.json"
    )

    rmsd_results, mr, summary = match_structures_multi_samples(
        gt_file=gt_file,
        pred_file=pred_file,
        num_cpus=args.num_cpus,
        stol=args.stol,
        ltol=args.ltol,
        angle_tol=args.angle_tol,
        num_samples=args.num_samples,
        output_csv=output_csv,
        output_json=output_json,
        verbose=True,
        show_sample_progress=True
    )

    # Save summary
    summary_json = os.path.join(results_dir, "all_atom_matching_summary.json")
    with open(summary_json, "w") as f:
        json.dump(summary, f, indent=4)
    print(f"  Summary saved: {summary_json}")

    # Step 3: Coarse-grained structure matching (optional, only if --cg is set)
    if args.cg and cg_xyz is not None:
        cg_gt_file = os.path.join(xyz_dir, cg_gt_xyz)
        cg_pred_file = os.path.join(xyz_dir, cg_xyz)
        
        if os.path.exists(cg_gt_file) and os.path.exists(cg_pred_file):
            print("\n[Step 3] Performing coarse-grained structure matching...")
            cg_output_csv = os.path.join(
                results_dir, 
                f"cg_rmsd_results_{args.num_samples}_stol{args.stol}.csv"
            )
            cg_output_json = os.path.join(
                results_dir, 
                f"cg_matching_summary_{args.num_samples}_stol{args.stol}.json"
            )

            cg_rmsd_results, cg_mr, cg_summary = match_structures_multi_samples(
                gt_file=cg_gt_file,
                pred_file=cg_pred_file,
                num_cpus=args.num_cpus,
                stol=0.5,  # Typically tighter tolerance for CG
                ltol=args.ltol,
                angle_tol=args.angle_tol,
                output_csv=cg_output_csv,
                output_json=cg_output_json,
                num_samples=args.num_samples,
                verbose=True,
                show_sample_progress=True
            )

            cg_summary_json = os.path.join(results_dir, "cg_matching_summary.json")
            with open(cg_summary_json, "w") as f:
                json.dump(cg_summary, f, indent=4)
            print(f"  CG Summary saved: {cg_summary_json}")

    # Final summary
    print("\n" + "=" * 60)
    print("Analysis Complete!")
    print("=" * 60)
    print(f"Overall match rate: {summary.get('overall_match_rate_percent', 0):.2f}%")
    if summary.get('mean_min_rmsd') is not None:
        print(f"Mean minimum RMSD: {summary['mean_min_rmsd']:.4f}")
        print(f"Std minimum RMSD: {summary['std_min_rmsd']:.4f}")
    print(f"Results saved in: {results_dir}")


if __name__ == "__main__":
    main()
